# Generates TRACEABILITY.md by scanning the citation tags in the code.
# Paper version: arXiv:2504.12189v1. Tags: [Paper §x], [Alg. k, step s], [Eq. (k)], [App. X], [Thm k], [Table k],
# [Fig. k], [ASSUMPTION: ...], [FROM AUTHORS' CODE: ...] (GitHub repository, commit 3b37682) and
# [FROM AUTHORS' SUPPLEMENT: ...] (ICLR 2025 supplementary material, code_final/).
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIRS = ["src/loostab", "experiments", "scripts"]
TAG = re.compile(r"\[(Paper|Alg\.|Eq\.|App\.|Thm|Table|Fig\.|ASSUMPTION|FROM AUTHORS' CODE|FROM AUTHORS' SUPPLEMENT)[^\]]*\]?")

# Paper element -> regex that locates its implementation tag(s)
ELEMENTS = [
    ("§2 FullCP set, Eq. (2); quantile Q_{1-alpha}(S u {inf})", r"\[Paper §2"),
    ("Eq. (2) / Alg. 5 FullCP grid search (App. C.2)", r"\[Alg\. 5"),
    ("Eq. (3) / Alg. 7 RO-StabCP (App. C.4)", r"\[Alg\. 7"),
    ("Alg. 1 LOO-StabCP (§3.1), steps 1-4", r"\[Alg\. 1"),
    ("Alg. 4 OracleCP (App. C.1)", r"\[Alg\. 4"),
    ("Alg. 6 SplitCP (App. C.3), 70/30 split (§4)", r"\[Alg\. 6"),
    ("Alg. 8 RLM, §3.2.1 objective; Omega = ||theta||^2 (§4)", r"\[Alg\. 8|Omega\(theta\)"),
    ("Alg. 9 SGD with reshuffling (§3.2.2); R=15, eta=0.001 (§4)", r"\[Alg\. 9|R=15"),
    ("Eq. (4) / Thm 2 RLM bounds; App. G.1 explicit form", r"\[App\. G\.1, RLM|\[Eq\. \(4\)\]"),
    ("Eq. (5) / Thm 3 SGD bounds; App. G.1 explicit form", r"\[App\. G\.1, SGD|\[Eq\. \(5\)\]"),
    ("Eq. (8) NN heuristic bound (§5, App. A.2)", r"\[Eq\. \(8\)\]"),
    ("§4 data-generating process (AR(1), beta, mu)", r"\[Paper §4: (Sigma|covariance|beta|linear|nonlinear|eps)"),
    ("§4 Huber loss, eps = 1", r"Huber|EPS_HUBER"),
    ("§4 alpha = 0.1", r"alpha = 0\.1"),
    ("§4 / §5 100 repetitions", r"repeated 100 times"),
    ("§5 real data (Boston, Diabetes), normalisation, hold-out m", r"\[Paper §5"),
    ("§5 Fig. 3 / App. A.2 Fig. 6 neural networks", r"Fig\. 3|Fig\. 6"),
    ("App. B Figs. 7-8 MM-/EM-SplitCP, 30 splits", r"\[App\. B"),
    ("App. A.1 Fig. 5 kernels (RBF, polynomial, kernel RLM/SGD)", r"\[App\. A\.1"),
    ("App. G.2 Table 2 (paper numbers)", r"Table 2"),
    ("App. G.3 Table 3 (paper numbers)", r"Table 3"),
]


def scan():
    hits = []
    for d in DIRS:
        for dp, _, fs in os.walk(os.path.join(ROOT, d)):
            for f in sorted(fs):
                if not f.endswith(".py"):
                    continue
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, ROOT)
                lines = open(p).read().splitlines()
                for i, line in enumerate(lines, 1):
                    if TAG.search(line):
                        # gather a multi-line ASSUMPTION comment
                        text = line.strip()
                        if "marks choices" in text or "Tags:" in text:
                            continue  # header lines explaining the convention
                        j = i
                        # an ASSUMPTION comment continues on following lines indented as "#  ..."
                        while "[ASSUMPTION" in text and j < len(lines) and lines[j].strip().startswith("#  "):
                            text += " " + lines[j].strip().lstrip("#").strip()
                            j += 1
                        hits.append((rel, i, text))
    return hits


def main():
    hits = scan()
    out = ["# TRACEABILITY", "",
           "Paper: Lee & Zhang, *Leave-One-Out Stable Conformal Prediction*, ICLR 2025, **arXiv:2504.12189v1** "
           "(arXiv PDF https://arxiv.org/pdf/2504.12189v1; not vendored here). Numbering follows the compiled PDF.", "",
           "This file is generated by `tools/traceability.py` from the `# [...]` tags in the code. "
           "Re-run it after editing the code.", "",
           "## 1. Paper element → code", "", "| Paper element | Code locations (file:line) |", "|---|---|"]
    for name, pat in ELEMENTS:
        rx = re.compile(pat)
        locs = sorted({f"{f}:{ln}" for f, ln, t in hits if rx.search(t)})
        out.append(f"| {name} | {', '.join(locs) if locs else '**not found**'} |")
    ass = [(f, ln, t) for f, ln, t in hits if "[ASSUMPTION" in t]
    auth = [(f, ln, t) for f, ln, t in hits if "[FROM AUTHORS' CODE" in t]
    supp = [(f, ln, t) for f, ln, t in hits if "FROM AUTHORS' SUPPLEMENT" in t]
    out += ["", f"## 2. All ASSUMPTION tags ({len(ass)})", "", "| # | file:line | Assumption |", "|---|---|---|"]
    for k, (f, ln, t) in enumerate(ass, 1):
        txt = t.split("[ASSUMPTION", 1)[1].lstrip(":").strip()
        txt = txt[:-1] if txt.endswith("]") else txt.replace("|", "\\|")
        out.append(f"| A{k} | {f}:{ln} | {txt} |")
    out += ["", f"## 3. FROM AUTHORS' CODE tags ({len(auth)})", ""]
    if auth:
        out += ["| file:line | Tag |", "|---|---|"] + [f"| {f}:{ln} | {t.replace('|', chr(92) + '|')} |" for f, ln, t in auth]
    else:
        out.append("None. The implementation was written from the paper alone, and the authors' code was only used afterwards, for diagnosis (see DISCREPANCIES.md).")
    out += ["", f"## 4. FROM AUTHORS' SUPPLEMENT tags ({len(supp)})", "",
            "Choices taken from the authors' ICLR 2025 supplementary material (`code_final/`, sha256 of the zip "
            "7f39cd75fda4e126ebdf5f545b34c3dbe2208f6216086e4137f23ef82a765e53), read after the GitHub repository. "
            "All are opt-in variants except `src/loostab/kernels.py`, which was written after reading the supplement.", ""]
    out += ["| file:line | Tag |", "|---|---|"] + [f"| {f}:{ln} | {t.replace('|', chr(92) + '|')} |" for f, ln, t in supp]
    out += ["", f"## 5. Every citation tag ({len(hits)})", "", "| file:line | Line |", "|---|---|"]
    for f, ln, t in hits:
        out.append(f"| {f}:{ln} | `{t[:160].replace('|', '/').replace('`', '')}` |")
    open(os.path.join(ROOT, "TRACEABILITY.md"), "w").write("\n".join(out) + "\n")
    print(f"TRACEABILITY.md: {len(hits)} tags, {len(ass)} assumptions")


if __name__ == "__main__":
    main()
